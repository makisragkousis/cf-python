"""Παράδειγμα συνάρτησης με προεπιλεγμένες παραμέτρους.

Λειτουργεί ως υπερφόρτωση συνάρτησης (function overloading)
και επιτρέπει την κλήση της ίδιας συνάρτησης με διαφορετικό αριθμό ορισμάτων.
"""


def say_hello(s = "Hello World!") -> None:
    """Εκτυπώνει ένα μήνυμα."""
    print(f"{s}")

def main() -> None:
    """Κύρια συνάρτηση που καλεί τη say_hello() με και χωρίς όρισμα."""
    say_hello()  # Κλήση χωρίς όρισμα, χρησιμοποιείται η προεπιλεγμένη τιμή
    say_hello("Γειά σου Κόσμε!")  # Κλήση με όρισμα


if __name__ == "__main__":
    main()