"""Υπολογισμός παραγοντικού αριθμού."""


def factorial(n: int) -> int:
    """Υπολογίζει το παραγοντικό ενός αριθμού n.

    Args:
        n (int): Ο αριθμός για τον οποίο θα υπολογιστεί το παραγοντικό.

    Returns:
        int: Το παραγοντικό του αριθμού n.
    """
    result = 1
    for i in range(1, n + 1):
        result *= i

    return result


def main() -> None:
    """Κύρια συνάρτηση για την εκτέλεση του προγράμματος."""
    n = int(input("Εισάγετε έναν ακέραιο για τον υπολογισμό του παραγοντικού: "))

    result = factorial(n)

    print(f"Το παραγοντικό του {n} είναι: {result}")


if __name__ == "__main__":
    main()

