"""A simple addition app."""

# Δημιουργία και αρχικοποίηση μεταβλητών
num1 = 10
num2 = 5

# Data Processing: Εκτέλεση πρόσθεσης
total = num1 + num2

# Data Output: Εκτύπωση του αποτελέσματος
print("Το άθροισμα των", num1, "και", num2, "είναι:", total)
print(f"Το άθροισμα των {num1} και {num2} είναι: {total}")          # f-string formatting