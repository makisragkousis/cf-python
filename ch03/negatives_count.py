"""Υπολογισμός του αριθμού των αρνητικών αριθμών σε μια λίστα."""


def main() -> None:
    """Κύρια συνάρτηση για την εκτέλεση του προγράμματος."""
    count = 0

    num = int(input("Εισάγετε έναν ακέραιο αριθμό (>=0 για έξοδο): "))

    while num < 0:
        count += 1
        num = int(input("Εισάγετε έναν ακέραιο αριθμό (>=0 για έξοδο): "))

    print(f"Ο αριθμός των αρνητικών αριθμών που εισήχθησαν είναι: {count}")

if __name__ == "__main__":
    main()