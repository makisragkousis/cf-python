"""Εύρεση της ελάχιστης τιμής μεταξύ δύο int."""


def min_val(a: int, b: int) -> int:
    """Επιστρέφει την ελάχιστη τιμή μεταξύ δύο ακέραιων αριθμών.

    Args:
        a (int): Ο πρώτος ακέραιος αριθμός.
        b (int): Ο δεύτερος ακέραιος αριθμός.

    Returns:
        int: Η ελάχιστη τιμή μεταξύ των δύο αριθμών.
    """
    if a < b:
        return a
    else:
        return b


def min_val_ternary(a: int, b: int) -> int:
    """Επιστρέφει την ελάχιστη τιμή μεταξύ δύο ακέραιων αριθμών χρησιμοποιώντας τον τελεστή ternary.

    Args:
        a (int): Ο πρώτος ακέραιος αριθμός.
        b (int): Ο δεύτερος ακέραιος αριθμός.

    Returns:
        int: Η ελάχιστη τιμή μεταξύ των δύο αριθμών.
    """
    return a if a < b else b        # conditional expression (ternary operator)


def min_py(a: int, b: int) -> int:
    """Επιστρέφει την ελάχιστη τιμή μεταξύ δύο ακέραιων αριθμών χρησιμοποιώντας τη συνάρτηση min().

    Args:
        a (int): Ο πρώτος ακέραιος αριθμός.
        b (int): Ο δεύτερος ακέραιος αριθμός.

    Returns:
        int: Η ελάχιστη τιμή μεταξύ των δύο αριθμών.
    """
    return min(a, b)