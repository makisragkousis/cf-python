"""Μενού επιλογών για την εφαρμογή με input choice και if-elif-else."""


def print_menu() -> None:
    """Εκτυπώνει το μενού επιλογών."""
    print("Επιλέξτε μια επιλογή:")
    print("1. Κατάθεση")
    print("2. Ανάληψη")
    print("3. Υπόλοιπο")
    print("4. Έξοδος")


def main() -> None:
    """Κύρια συνάρτηση για την εκτέλεση του προγράμματος."""
    while True:
        print_menu()
        choice = input("Εισάγετε την επιλογή σας (1-4): ")

        if choice == "1":
            print("Επιλέξατε Κατάθεση.")
            # Εδώ θα μπορούσε να προστεθεί η λογική για την κατάθεση
        elif choice == "2":
            print("Επιλέξατε Ανάληψη.")
            # Εδώ θα μπορούσε να προστεθεί η λογική για την ανάληψη
        elif choice == "3":
            print("Επιλέξατε Υπόλοιπο.")
            # Εδώ θα μπορούσε να προστεθεί η λογική για το υπόλοιπο
        elif choice == "4":
            print("Έξοδος από το πρόγραμμα.")
            break
        else:
            print("Μη έγκυρη επιλογή. Παρακαλώ προσπαθήστε ξανά.")


if __name__ == "__main__":
    main()