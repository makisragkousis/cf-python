"""Απόλυτη τιμή ενός ακεραίου με conditional expression."""


def abs_value(x: int) -> int:
    """Υπολογίζει την απόλυτη τιμή ενός ακεραίου x.

    Args:
        x (int): Ο ακέραιος για τον οποίο θα υπολογιστεί η απόλυτη τιμή.

    Returns:
        int: Η απόλυτη τιμή του ακεραίου x.
    """
    return x if x >= 0 else -x

def abs_python(x: int) -> int:
    """Υπολογίζει την απόλυτη τιμή ενός ακεραίου x χρησιμοποιώντας τη συνάρτηση abs().

    Args:
        x (int): Ο ακέραιος για τον οποίο θα υπολογιστεί η απόλυτη τιμή.

    Returns:
        int: Η απόλυτη τιμή του ακεραίου x.
    """
    return abs(x)


if __name__ == "__main__":
    num = int(input("Εισάγετε έναν ακέραιο αριθμό: "))
    print(f"Η απόλυτη τιμή του {num} είναι: {abs_value(num)}")
    print(f"Η απόλυτη τιμή του {num} χρησιμοποιώντας τη συνάρτηση abs() είναι: {abs_python(num)}")